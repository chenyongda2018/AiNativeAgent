#!/bin/bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
OUTPUT_DIR="$SCRIPT_DIR/../build/generated"
OUTPUT_FILE="$OUTPUT_DIR/LocalConfig.swift"

mkdir -p "$OUTPUT_DIR"

API_KEY=""

if [[ "${1:-}" == "--test-fake-key" ]]; then
    # 显式假值测试机制：仅用于安全测试，强制隔离任何真实凭据
    API_KEY="${2:-}"
elif [[ "${SAFE_DISABLE_CREDENTIALS:-0}" == "1" || "${SAFE_DISABLE_CREDENTIALS:-false}" == "true" || "${1:-}" == "--safe-disable-credentials" ]]; then
    # 强制安全禁用模式：强制为空，绝不触碰真实凭据
    API_KEY=""
else
    # 正常模式：先从环境变量获取，未设置才从 local.properties 获取
    if [[ -n "${DEEPSEEK_API_KEY:-}" ]]; then
        API_KEY="$DEEPSEEK_API_KEY"
    elif [[ -f "$PROJECT_ROOT/local.properties" ]]; then
        API_KEY=$(grep -E '^[[:space:]]*DEEPSEEK_API_KEY[[:space:]]*=' "$PROJECT_ROOT/local.properties" | head -n 1 | cut -d '=' -f2- | sed 's/^[[:space:]]*//;s/[[:space:]]*$//' || true)
    fi
fi

# 使用 Base64 编码方案生成 Swift 字符串，彻底避免引号、反斜杠、换行符、CR、Tab、反引号及 Swift 插值 \() 的转义歧义
BASE64_VALUE=$(printf '%s' "$API_KEY" | python3 -c '
import sys, base64
print(base64.b64encode(sys.stdin.buffer.read()).decode("ascii"))
')

cat <<EOF > "$OUTPUT_FILE"
// Generated by prepare-local-config.sh. Do not edit manually or commit credentials.
import Foundation

enum LocalConfig {
    static let deepSeekApiKey: String = {
        let base64 = "$BASE64_VALUE"
        if base64.isEmpty { return "" }
        guard let data = Data(base64Encoded: base64),
              let str = String(data: data, encoding: .utf8) else {
            return ""
        }
        return str
    }()
}
EOF
